-- 814_partner_payee_kana_fix.sql — 取引先口座の受取人名を半角カナに直す（BUG-0418）
--
-- 取引先口座の登録画面は 2026-08-19 まで検証つきハンドラが繋がっておらず（BUG-0045）、
-- **全角カナのまま保存された行が 2 件**残っていた（`グランメゾンインサツ（カ` / `ホライゾンショウジ（カ`）。
-- 全銀フォーマットは半角カナしか受け付けないので、この 2 社は振込データから
-- 「受取人名に使用できない文字があります: グ」で除外されていた。
-- FB を作る人は除外理由を読まないと気づけないし、
-- 体験シナリオ 購買-02 の期待値（グランメゾン 2 件が含まれる）も満たせなかった。
--
-- 元の表記（会社名のうしろに `（カ`）を保ったまま半角へ移す。
-- **いまの値がその全角表記と一致するときだけ**直す（他環境で別の値なら何もしない）。

UPDATE partners
   SET payee_kana = 'ｸﾞﾗﾝﾒｿﾞﾝｲﾝｻﾂ(ｶ'
 WHERE code = 'C005' AND payee_kana = 'グランメゾンインサツ（カ';

UPDATE partners
   SET payee_kana = 'ﾎﾗｲｿﾞﾝｼｮｳｼﾞ(ｶ'
 WHERE code = 'C007' AND payee_kana = 'ホライゾンショウジ（カ';

-- 小書きカナ（ｼｮ）も全銀では使えない。大書き（ｼﾖ）に直す。
-- `ｶ)ﾃﾂｸｲﾉﾍﾞｰｼﾖﾝ`（テックイノベーション）は最初から正しく大書きで入っており、こちらが手本。
