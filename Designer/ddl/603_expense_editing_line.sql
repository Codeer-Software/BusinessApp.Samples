-- 603_expense_editing_line.sql — 経費申請に「編集中の明細」への参照を持たせる（ADR-0066 の UI 作り直し）
--
-- 経緯: 明細行化の第 1 版は「1 行に 15 列を横スクロールで詰め込む」画面になり、
--   ユーザーから「パッと見て何をすればいいか分からない」「1 行の情報が多すぎる」との指摘を受けた。
--   あわせて AI 読み取りが壊れていた（ヘッダの受け皿経由で行を作っていたため、
--   AI が明細行にも書く回に二重行・既存行の上書きが起きていた）。
--
-- 作り直しの形（ユーザー提案の 4 ブロック構成）:
--   1. この申請について（件名・目的・計上日・支払先など）
--   2. **明細 1 件分の入力フォーム**（＝この列が指す行）＋「この内容で追加」
--   3. 追加した明細のリスト（line_no を採番済みの行）
--   4. 承認
--
-- editing_line_id は「いま 2 のフォームで編集している明細行」を指す。
--   確定していない行は line_no が NULL で、3 のリスト（line_no >= 1 で絞る）には出ない。
--   これにより、AI 読み取り・領収書の添付が**最初からその行のもの**になり、
--   「フォームから行へファイルをコピーする」必要が無くなる
--   （CLB のスクリプトからは FileField の実体（FileGuid/FileSize）に触れないため、コピーは不可能）。

ALTER TABLE expense_request ADD COLUMN editing_line_id INTEGER REFERENCES expense_request_lines(id);
