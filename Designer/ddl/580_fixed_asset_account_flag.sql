-- 580_fixed_asset_account_flag.sql — 勘定科目に「固定資産科目」フラグを足す（ADR-0063・BusinessAppSQLite）
--
-- 【問題】固定資産台帳の「資産計上科目」の候補が「科目区分 = 資産 かつ 有効」だけで絞られており、
--   現金・普通預金・売掛金・貸倒引当金まで選べた（有効な資産科目 18 件が全部出る）。
--   この科目は**減価償却仕訳の貸方**になる（FixedAsset.mod.cs の GenerateDep）ため、
--   誤って現金を選ぶと「借 減価償却費 / 貸 現金」となり、現金残高が毎年静かに減る。
--   しかも減価償却は内部振替で税区分を対象外に上書きする（ADR-0053）ので消費税集計表にも出ず、
--   気づく手がかりが翌期の残高照合まで無い。
--
-- 【なぜ表示区分（account_categories）で絞らないか】
--   表示区分は「財務諸表のどこに並べるか」であって「この画面で選ばせてよいか」ではない。
--   固定資産台帳は非償却（償却方法「非償却」）の資産も持てる一方、
--   投資その他の資産（敷金保証金・長期前払費用）は減価償却資産台帳の対象ではない、
--   というように**区分と台帳の対象は一致しない**。用途はマスタの列として持たせる。
--   先例: `is_cash_equivalent`（現預金科目・ADR-0055）— 「入出金起票で選べる科目」を同じ形で持っている。
--
-- 【名前】「償却資産科目」ではなく「固定資産科目」。台帳は非償却資産も持てるので、
--   フラグが意味するのは「固定資産台帳の計上科目として選べるか」。
--   フラグは名乗ったとおりの場所で効かせる（ADR-0054 の教訓）:
--     ①FixedAsset.AssetAccount の候補条件（登録・検索）②減価償却仕訳の生成ガード。

ALTER TABLE accounts ADD COLUMN is_fixed_asset_account INTEGER NOT NULL DEFAULT 0;

-- 有形固定資産・無形固定資産のみを対象にする。
--   1500 建物附属設備 / 1520 工具器具備品 … 有形固定資産
--   1560 ソフトウェア                     … 無形固定資産
--   1570 ソフトウェア仮勘定               … 無形固定資産。完成前は「非償却」で台帳に載せ、完成時に本勘定へ振り替える
-- 除外:
--   1600 敷金保証金 / 1630 長期前払費用   … 投資その他の資産。減価償却資産台帳の対象ではない
--   流動資産 12 件（現金・預金・売掛金・貸倒引当金 等）
UPDATE accounts SET is_fixed_asset_account = 1 WHERE code IN ('1500', '1520', '1560', '1570');

-- 確認
SELECT code, name, is_fixed_asset_account FROM accounts WHERE account_type = 'asset' ORDER BY code;
