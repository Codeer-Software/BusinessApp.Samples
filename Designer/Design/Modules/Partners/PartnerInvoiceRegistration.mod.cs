//
// 出所（source）と公表システム側の更新年月日（nta_updated_on）は、この画面が扱わない。
// 手入力の行は DB の既定（source = 'manual'）が入る。取込を作るときに画面へ出すか決める。
//
// 取引先の候補は **IsActive で絞ったままにする**（名寄せの親とは扱いを変える。2026-08-30 の判断）。
// 名寄せの親を絞らないのは「同一人格の表明であって入力候補ではない」から（ADR-0028）だが、
// **登録番号はその取引先と取引する前提の入力**なので、無効にした相手を新しく選ぶ場面が無い。
// 既に選んである相手が無効になっても、現在値は候補に残るので表示は壊れない（qa/01 X-05）。

// 既にある登録の取引先を、付け替えられると見せない。
//
// **付け替えると A 社の履歴に穴が空き、B 社に他人の登録番号が生える**（docs/07 §3-4）。
// しかも計上済みの明細に焼き込んだ写しと食い違い、計上済みは直せない（ADR-0004）。
//
// **守っているのは Partner フィールドの IsUpdateProtected である**——サーバ側でも拒むことを
// 実機で確かめた（2026-08-30。1.3.20。qa/01 F-26）。ここでやっているのは表示の話で、
// **守りに数えない**（*.mod.cs は WASM 側で走り、URL 直指定と API を素通りする。qa/01 F-24）。
//
// それでも要る理由は docs/09 §1——**書けない状態の画面は、書けないと見て分かるようにする。**
// これが無いと、選び直せるように見えて、押した先で
// 「Partner This field cannot be modified」が返る（英語のうえにフィールド名がそのまま出る）。
//
// **新規では選ばせる。** IsUpdateProtected も更新のときだけ効く。
